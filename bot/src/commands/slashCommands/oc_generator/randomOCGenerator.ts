import { EmbedBuilder } from "@discordjs/builders";
import { ChatInputCommandInteraction, SlashCommandBuilder } from "discord.js";
import { Command } from "../../../interfaces/Command";
import {
  randomizeEyeColor,
  randomizeGender,
  randomizeHairColor,
  randomizeHairLength,
  randomizeHeterochromia,
  randomizeSexuality,
  randomizeSpecies,
} from "./utils";

export const RandomOCGenerator: Command = {
  data: new SlashCommandBuilder()
    .setName("ocgen")
    .setDescription("Gives you a random OC."),
  run: async (interaction: ChatInputCommandInteraction) => {
    try {
      await interaction.deferReply();

      const randomOCEmbed = new EmbedBuilder();

      randomOCEmbed.setTitle("Random OC Generator");
      randomOCEmbed.setDescription("Here is your random OC!");

      const heterochromia = randomizeHeterochromia();
      const eyeColor = randomizeEyeColor(heterochromia);
      randomOCEmbed.addFields(
        {
          name: "Gender",
          value: randomizeGender(),
        },
        {
          name: "Species",
          value: randomizeSpecies(),
        },
        {
          name: "Sexuality",
          value: randomizeSexuality(),
        },
        {
          name: "Hair color",
          value: randomizeHairColor().join(", "),
        },
        {
          name: "Hair length",
          value: randomizeHairLength(),
        },
        {
          name: "Eye color",
          value: Array.isArray(eyeColor) ? eyeColor.join(" & ") : eyeColor,
        },
        {
          name: "Heterochromia",
          value: heterochromia,
        },
      );
      randomOCEmbed.setFooter({
        text: "Generated by DimSum",
      });
      await interaction.editReply({
        embeds: [randomOCEmbed],
      });
    } catch (error) {
      console.log(error);
    }
  },
};
