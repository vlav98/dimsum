import { ChatInputCommandInteraction, SlashCommandBuilder } from "discord.js";
import { Command } from "../../../../interfaces/Command";
import { savePromptButton } from "../../../../promptComponents";
import { generateRandomOC } from "../../../../generators/writing";
import { addCharacterOptions, getCharacterOptions } from "./options";

export const RandomOCGenerator: Command = {
  data: addCharacterOptions(
    new SlashCommandBuilder()
      .setName("ocgen")
      .setDescription(
        "Generate an OC; leave properties blank to randomize them.",
      ),
  ),
  run: async (interaction: ChatInputCommandInteraction) => {
    try {
      await interaction.deferReply();

      const randomOCEmbed = generateRandomOC(
        getCharacterOptions(interaction),
      ).setFooter({ text: "Generated by DimSum" });
      await interaction.editReply({
        embeds: [randomOCEmbed],
        components: [savePromptButton("oc")],
      });
    } catch (error) {
      console.error("Could not generate an OC:", error);
      await interaction.editReply(
        "The OC could not be generated. Please try again.",
      );
    }
  },
};
