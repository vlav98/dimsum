import { randomUUID } from "node:crypto";
import {
  ActionRowBuilder,
  ButtonBuilder,
  ButtonInteraction,
  ButtonStyle,
  ChatInputCommandInteraction,
  MessageFlags,
  StringSelectMenuBuilder,
  StringSelectMenuInteraction,
} from "discord.js";
import { savePromptButton } from "../../../../components/common/promptButtons/promptButtons";
import {
  CharacterOptions,
  generateOC,
  generateRandomOC,
  getOmissionChoices,
  InvalidOmittedPropertyError,
} from "../../../../generators/writing";
import { getCharacterOptions } from "./options";

type Generator = "random" | "sheet";

interface PendingSelection {
  userId: string;
  generator: Generator;
  style?: string | null;
  section?: string | null;
  options: CharacterOptions;
  omitted: string[];
  expiresAt: number;
}

const selectionTimeoutMs = 15 * 60 * 1000;
const pendingSelections = new Map<string, PendingSelection>();

function selectionRows(
  id: string,
  generator: Generator,
  omitted: string[],
): ActionRowBuilder<StringSelectMenuBuilder | ButtonBuilder>[] {
  const choices = getOmissionChoices(generator === "sheet");
  const selector = new StringSelectMenuBuilder()
    .setCustomId(`oc-omit:${id}`)
    .setPlaceholder("Choose properties to omit")
    .setMinValues(0)
    .setMaxValues(choices.length)
    .addOptions(
      choices.map(({ name, value }) => ({
        label: name,
        value,
        default: omitted.includes(value),
      })),
    );
  const generate = new ButtonBuilder()
    .setCustomId(`oc-generate:${id}`)
    .setLabel("Generate OC")
    .setStyle(ButtonStyle.Primary);
  return [
    new ActionRowBuilder<StringSelectMenuBuilder>().addComponents(selector),
    new ActionRowBuilder<ButtonBuilder>().addComponents(generate),
  ];
}

function selectionPrompt() {
  return "Select any properties to omit, then choose **Generate OC**. Custom values are used unless omitted; all other properties are randomized.";
}

function removeExpiredSelections() {
  const now = Date.now();
  for (const [id, selection] of pendingSelections) {
    if (selection.expiresAt <= now) pendingSelections.delete(id);
  }
}

function generateEmbed(
  generator: Generator,
  style: string | null | undefined,
  section: string | null | undefined,
  options: CharacterOptions,
) {
  return generator === "random"
    ? generateRandomOC(options).setFooter({ text: "Generated by DimSum" })
    : generateOC(style, section, options);
}

export async function beginOCGeneration(
  interaction: ChatInputCommandInteraction,
  generator: Generator,
  style?: string | null,
  section?: string | null,
  showOmissionSelector = false,
): Promise<void> {
  if (!showOmissionSelector) {
    let embed: ReturnType<typeof generateEmbed>;
    try {
      embed = generateEmbed(
        generator,
        style,
        section,
        getCharacterOptions(interaction),
      );
    } catch (error) {
      console.error("Could not generate an OC:", error);
      await interaction.reply({
        content:
          error instanceof InvalidOmittedPropertyError
            ? error.message
            : "The OC could not be generated. Please try again.",
        flags: MessageFlags.Ephemeral,
      });
      return;
    }
    await interaction.reply({
      embeds: [embed],
      components: [savePromptButton("oc")],
      allowedMentions: { parse: [] },
    });
    return;
  }

  await interaction.deferReply({ flags: MessageFlags.Ephemeral });
  try {
    const options = getCharacterOptions(interaction);
    const omitted: string[] = [];
    const id = randomUUID();
    removeExpiredSelections();
    pendingSelections.set(id, {
      userId: interaction.user.id,
      generator,
      style,
      section,
      options,
      omitted,
      expiresAt: Date.now() + selectionTimeoutMs,
    });
    const components = selectionRows(id, generator, omitted);
    await interaction.editReply({
      content: selectionPrompt(),
      components,
    });
  } catch (error) {
    if (error instanceof InvalidOmittedPropertyError) {
      await interaction.editReply(error.message);
      return;
    }
    console.error("Could not start OC generation:", error);
    await interaction.editReply(
      "OC generation could not be configured. Please try again.",
    );
  }
}

async function getPendingSelection(
  interaction: StringSelectMenuInteraction | ButtonInteraction,
  id: string,
): Promise<PendingSelection | undefined> {
  const selection = pendingSelections.get(id);
  if (!selection || selection.expiresAt <= Date.now()) {
    pendingSelections.delete(id);
    await interaction.reply({
      content: "This OC setup expired. Run the command again.",
      flags: MessageFlags.Ephemeral,
    });
    return;
  }
  if (selection.userId !== interaction.user.id) {
    await interaction.reply({
      content: "This OC setup belongs to another user.",
      flags: MessageFlags.Ephemeral,
    });
    return;
  }
  return selection;
}

export async function updateOCOmissions(
  interaction: StringSelectMenuInteraction,
): Promise<void> {
  const id = interaction.customId.slice("oc-omit:".length);
  const selection = await getPendingSelection(interaction, id);
  if (!selection) return;

  const allowed = new Set<string>(
    getOmissionChoices(selection.generator === "sheet").map(
      ({ value }) => value,
    ),
  );
  if (interaction.values.some((value) => !allowed.has(value))) {
    await interaction.reply({
      content: "That property selection is invalid. Run the command again.",
      flags: MessageFlags.Ephemeral,
    });
    return;
  }
  selection.omitted = [...new Set(interaction.values)];
  selection.expiresAt = Date.now() + selectionTimeoutMs;
  await interaction.update({
    content: selectionPrompt(),
    components: selectionRows(id, selection.generator, selection.omitted),
  });
}

export async function generateSelectedOC(
  interaction: ButtonInteraction,
): Promise<void> {
  const id = interaction.customId.slice("oc-generate:".length);
  const selection = await getPendingSelection(interaction, id);
  if (!selection) return;
  pendingSelections.delete(id);

  const options = {
    ...selection.options,
    omit: selection.omitted.join(", "),
  };
  try {
    const embed = generateEmbed(
      selection.generator,
      selection.style,
      selection.section,
      options,
    );
    await interaction.update({
      content: "Your OC has been generated in the channel.",
      embeds: [],
      components: [],
    });
    await interaction.followUp({
      embeds: [embed],
      components: [savePromptButton("oc")],
      allowedMentions: { parse: [] },
    });
  } catch (error) {
    console.error("Could not generate an OC:", error);
    const message =
      error instanceof InvalidOmittedPropertyError
        ? error.message
        : "The OC could not be generated. Please try again.";
    if (interaction.deferred || interaction.replied) {
      await interaction.followUp({
        content: message,
        flags: MessageFlags.Ephemeral,
      });
    } else {
      await interaction.reply({
        content: message,
        flags: MessageFlags.Ephemeral,
      });
    }
  }
}
